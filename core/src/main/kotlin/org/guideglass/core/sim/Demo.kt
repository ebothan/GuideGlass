package org.guideglass.core.sim

import org.guideglass.core.CueKind
import org.guideglass.core.Earcon
import org.guideglass.core.cloud.CloudGuard
import org.guideglass.core.SafetyPipeline
import org.guideglass.core.sim.Runner.Companion.percentile
import java.io.File

/*
 * End-to-end desktop run (gate G2a, labelled L3-substitute: JVM, mock frame source, logging audio sink)
 * and the latency report (gate G3). Run: ./gradlew -p core runDemo
 *
 * Writes docs/results/latency_report.md, docs/results/demo_cue_log.md and, under core/build/demo/,
 * one replayable JSON Lines event log per demo scenario.
 */

private data class StageBudget(val name: String, val p95Ms: Double, val source: String)

private val BUDGET = listOf(
    StageBudget("1 glasses capture+encode", 90.0, "drawn from the assumed budget distribution [A]"),
    StageBudget("2 bluetooth video", 180.0, "drawn [A]; spikes are injected faults"),
    StageBudget("3 decode", 40.0, "drawn [A]"),
    StageBudget("4 queue wait", 40.0, "drawn [A]"),
    StageBudget("5a detector", 30.0, "drawn [A]; read figure 1.6 ms (05)"),
    StageBudget("5b depth", 50.0, "drawn [A]; read figure 22-34 ms (05)"),
)

fun main(args: Array<String>) {
    val docs = File(args.getOrElse(0) { "docs/results" }).apply { mkdirs() }
    val buildDir = File("core/build/demo").apply { mkdirs() }
    val runner = Runner(pipelineFactory = { SafetyPipeline(it, guard = CloudGuard()) })

    // ---------------------------------------------------------------- latency over the scenario suite
    val suite: List<(Long) -> Scenario> = listOf(
        { Scenarios.s01Person(it) }, { Scenarios.s02Pole(it) }, { Scenarios.s03Bin(it) }, { Scenarios.s03LowBollard(it) },
        { Scenarios.s04HeadHeight(it) }, { Scenarios.s07DoubleApproach(it) }, { Scenarios.s09PersonToward(it) },
        { Scenarios.s10BikeToward(it) }, { Scenarios.s18Barrier(it) }, { Scenarios.s19Crowd(it) },
    )
    val runs = suite.flatMap { b -> (1L..30L).map { runner.run(b(it)) } }
    val stages = linkedMapOf<String, MutableList<Double>>()
    for (r in runs) for ((k, v) in r.stages) stages.getOrPut(k) { mutableListOf() } += v
    val compute = runs.flatMap { it.coreComputeS }

    val md = StringBuilder()
    fun ms(x: Double) = "%.1f".format(x * 1000)
    md.appendLine("# Latency report (gate G3)")
    md.appendLine()
    md.appendLine("Generated by `core/src/main/kotlin/org/guideglass/core/sim/Demo.kt` over ${runs.size} scenario runs " +
        "(10 obstacle scenarios x 30 seeds, ${stages["1 glasses capture+encode"]?.size ?: 0} frames).")
    md.appendLine()
    md.appendLine("**Read this first.** Stages 1-5 and the Bluetooth audio stage cannot be measured without the glasses and a phone.")
    md.appendLine("In this report they are *drawn* from distributions chosen to match the assumed budget in")
    md.appendLine("`docs/00-problem-constraints-goals.md` section 7, so their pass marks only confirm the arithmetic. What is")
    md.appendLine("measured here is (a) the decision core's own compute time on this desktop JVM [M, desktop proxy, not a phone],")
    md.appendLine("(b) the time cues wait in the arbiter behind other cues, and (c) how the prediction to the ear behaves end to end.")
    md.appendLine()
    md.appendLine("## Per stage")
    md.appendLine()
    md.appendLine("| Stage | p50 ms | p95 ms | p99 ms | Budget p95 ms | Result | Evidence |")
    md.appendLine("|---|---|---|---|---|---|---|")
    for (b in BUDGET) {
        val xs = stages[b.name] ?: continue
        val p95 = percentile(xs, 0.95)
        md.appendLine("| ${b.name} | ${ms(percentile(xs, 0.5))} | ${ms(p95)} | ${ms(percentile(xs, 0.99))} | %.0f | %s | ${b.source} |"
            .format(b.p95Ms, if (p95 * 1000 <= b.p95Ms) "pass" else "fail"))
    }
    val c95 = percentile(compute, 0.95)
    md.appendLine("| 6 core: track + decide + arbitrate | ${"%.3f".format(percentile(compute, 0.5) * 1000)} | ${"%.3f".format(c95 * 1000)} | " +
        "${"%.3f".format(percentile(compute, 0.99) * 1000)} | 10 | ${if (c95 * 1000 <= 10) "pass" else "fail"} | **measured** on desktop JVM (Apple M4); phone will be slower |")
    md.appendLine("| 7a earcon start | 20.0 | 20.0 | 20.0 | 40 | config | configuration value [A], not measured |")
    md.appendLine("| 7b speech start | 150.0 | 150.0 | 150.0 | 300 | config | configuration value [A], not measured |")
    md.appendLine("| 8 bluetooth audio | (drawn 150-300) | | | 300 | n/a | drawn [A]; must be measured on hardware (checklist H-3) |")
    md.appendLine()
    md.appendLine("## Per cue type, capture to ear")
    md.appendLine()
    md.appendLine("Budget p95: 780 ms to an earcon, 1040 ms to speech (docs/00 section 7). Queue wait is measured: it is the time a")
    md.appendLine("cue waited behind another cue in the arbiter.")
    md.appendLine()
    md.appendLine("| Cue type | n | p50 ms | p95 ms | p99 ms | Budget p95 ms | Result | Queue wait p95 ms |")
    md.appendLine("|---|---|---|---|---|---|---|---|")
    val byKind = runs.flatMap { it.cues }.filter { it.captureT != null }.groupBy { it.kind }
    for ((k, cs) in byKind.toSortedMap()) {
        val e2e = cs.map { it.earT - it.captureT!! }
        val wait = cs.map { it.play.startT - it.play.cue.requestedAt }
        val budget = if (cs.first().play.cue.earcon == Earcon.NONE) 1040.0 else 780.0
        val p95 = percentile(e2e, 0.95) * 1000
        md.appendLine("| $k | ${cs.size} | ${ms(percentile(e2e, 0.5))} | %.1f | ${ms(percentile(e2e, 0.99))} | %.0f | %s | ${ms(percentile(wait, 0.95))} |"
            .format(p95, budget, if (p95 <= budget) "pass" else "fail"))
    }
    // Health cues: from the triggering event to the ear.
    val lostDelays = (1L..30L).map { s ->
        val r = runner.run(Scenarios.f01CameraGap(s))
        val lost = r.of(CueKind.CAMERA_LOST).first()
        var last = 0.0; var prev: Long? = null
        for ((t, h) in r.deliveries) { if (t > lost.play.startT) break; if (h != prev) last = t; prev = h }
        lost.earT - last
    }
    val glassesDelays = (1L..30L).map { s -> runner.run(Scenarios.f05LinkLoss(s)).of(CueKind.GLASSES_LOST).first().earT - 4.0 }
    md.appendLine("| CAMERA_LOST (last fresh frame to ear) | 30 | ${ms(percentile(lostDelays, 0.5))} | ${ms(percentile(lostDelays, 0.95))} | " +
        "${ms(percentile(lostDelays, 0.99))} | 1000 | ${if (percentile(lostDelays, 0.95) <= 1.0) "pass" else "fail"} | - |")
    md.appendLine("| GLASSES_LOST (link down to ear, phone speaker) | 30 | ${ms(percentile(glassesDelays, 0.5))} | ${ms(percentile(glassesDelays, 0.95))} | " +
        "${ms(percentile(glassesDelays, 0.99))} | 1000 | ${if (percentile(glassesDelays, 0.95) <= 1.0) "pass" else "fail"} | - |")
    md.appendLine()
    md.appendLine("The phone-speaker route has no Bluetooth audio stage, but this run draws the same audio latency for every route, so")
    md.appendLine("the GLASSES_LOST figure is conservative.")
    File(docs, "latency_report.md").writeText(md.toString())

    // ---------------------------------------------------------------- end-to-end demo log (G2a)
    val demo = listOf(Scenarios.s01Person(1, true), Scenarios.s07DoubleApproach(1), Scenarios.s10BikeToward(1),
        Scenarios.s19Crowd(1), Scenarios.f01HazardDuringGap(1), Scenarios.f05LinkLoss(1), Scenarios.f03LowFps(1))
    val log = StringBuilder()
    log.appendLine("# End-to-end desktop run: what the user would hear (gate G2a)")
    log.appendLine()
    log.appendLine("Evidence label: **L3-substitute** (full decision pipeline on the desktop JVM, synthetic frame source, logging")
    log.appendLine("audio sink). Not an emulator run and not a real device. Times are seconds from start; `ear` includes drawn audio")
    log.appendLine("latency. Each run's complete input stream is saved as JSON Lines under `core/build/demo/` and replays to the")
    log.appendLine("same cues (ReplayTest).")
    for (sc in demo) {
        val r = runner.run(sc)
        val file = File(buildDir, sc.name.substringBefore(' ') + ".jsonl")
        EventLog.write(r.events, file)
        val replay = EventLog.replay(EventLog.read(file)).map { it.startT to it.cue.text }
        val same = replay == r.pipeline.log.map { it.play.startT to it.play.cue.text }
        log.appendLine()
        log.appendLine("## ${sc.name}")
        log.appendLine()
        log.appendLine("Obstacle contact: ${r.contactT.values.firstOrNull()?.let { "%.2f s".format(it) } ?: "none"}" +
            "${if (sc.walkerReacts) " (simulated walker stops on STOP)" else ""}. " +
            "Replay of the saved event log (${r.events.size} events) gives identical cues: **$same**.")
        log.appendLine()
        log.appendLine("| start s | ear s | route | cue | text |")
        log.appendLine("|---|---|---|---|---|")
        for (c in r.cues) log.appendLine("| %.2f | %.2f | ${c.play.route} | ${c.kind} | ${c.text}${c.play.interrupted?.let { " (cut off $it)" } ?: ""} |"
            .format(c.play.startT, c.earT))
    }
    val (route, how) = RouteSource.load()
    val nav = NavSim.run(route, NavWalk(listOf(Segment(330.0 / 1.3 + 5, 1.3)), seed = 1))
    log.appendLine()
    log.appendLine("## Navigation A to B on a replayed GPS trace ($how)")
    log.appendLine()
    log.appendLine("| t s | true distance along route m | cue | text |")
    log.appendLine("|---|---|---|---|")
    for (c in nav.cues) log.appendLine("| %.0f | %.1f | ${c.cue.kind} | ${c.cue.text} |".format(c.cue.requestedAt, c.trueAlongM))
    File(docs, "demo_cue_log.md").writeText(log.toString())
    println(md)
    println("wrote ${File(docs, "latency_report.md")} and ${File(docs, "demo_cue_log.md")}")
}
