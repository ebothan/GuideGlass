package org.guideglass.core.sim

import org.guideglass.core.CueKind
import java.io.File

/*
 * Rates over 300 seeds (1001-1300, not used while tuning) with 95% Wilson intervals, written to
 * docs/results/scenario_rates.md. Added after the adversarial review (finding 6): earlier documents quoted
 * rates from one 30-seed window. Run: ./gradlew -p core runSurvey
 */
fun main(args: Array<String>) {
    val out = File(args.getOrElse(0) { "docs/results" }).apply { mkdirs() }
    val runner = Runner()
    val seeds = 1001L..1300L
    val n = seeds.count()
    fun pct(k: Int): String { val (lo, hi) = BaselineEvaluator.wilson(k, n); return "%d/%d = %.1f%% [%.1f, %.1f]".format(k, n, 100.0 * k / n, lo, hi) }
    val md = StringBuilder()
    md.appendLine("# Scenario rates over 300 seeds")
    md.appendLine()
    md.appendLine("Generated by `core/src/main/kotlin/org/guideglass/core/sim/Survey.kt`. Seeds 1001-1300, none used while the logic")
    md.appendLine("was tuned. Brackets are 95% Wilson intervals. Evidence rung **L1**: synthetic world, a detection is assumed to")
    md.appendLine("exist for every object, range errors are assumed (30% depth scale, 2 degree pitch), delays are drawn from the budget.")
    md.appendLine()
    md.appendLine("## Scenes where no STOP should be given")
    md.appendLine()
    md.appendLine("| Scenario | Runs with a false STOP | Runs with any CAUTION or \"approaching\" cue |")
    md.appendLine("|---|---|---|")
    val quiet: List<Pair<String, (Long) -> Scenario>> = listOf(
        "S-05 parked car beside the path" to { s -> Scenarios.s05Beside(s) },
        "S-06 wall never closer than 7.4 m" to { s -> Scenarios.s06FarWall(s) },
        "S-11 cyclist crossing well ahead" to { s -> Scenarios.s11BikeCrossingClear(s) },
        "S-12 pedestrian ahead at the same pace" to { s -> Scenarios.s12SameDirection(s) },
        "S-13 fast head turns past roadside objects" to { s -> Scenarios.s13HeadSweep(s) },
    )
    for ((name, b) in quiet) {
        val runs = seeds.map { runner.run(b(it)) }
        md.appendLine("| $name | ${pct(runs.count { it.of(CueKind.STOP).isNotEmpty() })} | " +
            "${pct(runs.count { r -> r.cues.any { it.kind == CueKind.CAUTION || it.kind == CueKind.MOVING_OBJECT } })} |")
    }
    md.appendLine()
    md.appendLine("## Obstacles in the path: does a simulated walker who stops on STOP make contact?")
    md.appendLine()
    md.appendLine("Walker models (docs/00 section 8.1): typical = 0.15 s to recognise the earcon, 0.5 s reaction, 0.7 m to stop;")
    md.appendLine("conservative = 0.15 s, 1.0 s, 1.4 m. \"Late\" = the STOP reached the ear less than 1.36 s before open-loop contact.")
    md.appendLine()
    md.appendLine("| Scenario | Contact, typical walker | Contact, conservative walker | Runs with more than one STOP |")
    md.appendLine("|---|---|---|---|")
    fun slow(s: Scenario) = s.copy(reactionS = 1.0, stopDistanceM = 1.4)
    val hazards: List<Pair<String, (Long) -> Scenario>> = listOf(
        "S-01 person standing" to { s -> Scenarios.s01Person(s, true) },
        "S-02 pole" to { s -> Scenarios.s02Pole(s, true) },
        "S-03 bin" to { s -> Scenarios.s03Bin(s, true) },
        "S-03 low bollard" to { s -> Scenarios.s03LowBollard(s, true) },
        "S-04 head-height branch" to { s -> Scenarios.s04HeadHeight(s, true) },
        "S-18 barrier" to { s -> Scenarios.s18Barrier(s, true) },
        "S-03 bin, walker at 0.6 m/s" to { s -> Scenarios.s03Bin(s, true).copy(walk = listOf(Segment(20.0, 0.6))) },
        "S-01 person, 5 fps" to { s -> Scenarios.s01Person(s, true).copy(faults = Faults(fps = 5.0)) },
        "S-01 person, 7 fps" to { s -> Scenarios.s01Person(s, true).copy(faults = Faults(fps = 7.0)) },
        "S-01 person, 10 fps with 20% frame loss" to { s -> Scenarios.s01Person(s, true).copy(faults = Faults(fps = 10.0, dropProb = 0.2)) },
        "S-01 person, +0.4 s transport latency" to { s -> Scenarios.s01Person(s, true).copy(faults = Faults(extraLatency = listOf(0.0..20.0 to 0.4))) },
        "S-01 person, low light" to { s -> Scenarios.s01Person(s, true).copy(faults = Faults(darkFrom = 0.0)) },
        "S-03 bin, 40% of detections dropped" to { s -> Scenarios.s03Bin(s, true, 0.6) },
        "Person first visible 3.0 m ahead" to { s -> Scenario("late person", listOf(Obstacle(1, "person", 7.2, 0.1, 1.7, 0.5, appearsAt = 3.0)),
            listOf(Segment(9.0, 1.4)), walkerReacts = true, seed = s) },
        "S-09 pedestrian walking toward the user (stops only the user)" to { s -> Scenarios.s09PersonToward(s, true) },
    )
    for ((name, b) in hazards) {
        val typ = seeds.map { runner.run(b(it)) }
        val con = seeds.map { runner.run(slow(b(it))) }
        md.appendLine("| $name | ${pct(typ.count { r -> r.contactT.values.any { it != null } })} | " +
            "${pct(con.count { r -> r.contactT.values.any { it != null } })} | ${pct(typ.count { it.of(CueKind.STOP).size > 1 })} |")
    }
    md.appendLine()
    md.appendLine("## The conservative setting (reaction 1.0 s, stopping distance 1.4 m configured for the user)")
    md.appendLine()
    md.appendLine("The STOP lead follows the configured human model, so a user set up as a conservative walker is warned earlier.")
    md.appendLine("Cost: more false STOPs on the scenes where none should be given.")
    md.appendLine()
    md.appendLine("| Scenario | Contact, conservative walker, conservative setting | | Quiet scene | False STOP, conservative setting |")
    md.appendLine("|---|---|---|---|---|")
    val cons = Runner(org.guideglass.core.CoreConfig(reactS = 1.0, stopDistanceM = 1.4))
    val hz = hazards.take(7); 
    for (k in hz.indices) {
        val (name, bld) = hz[k]
        val c = seeds.count { sd -> cons.run(slow(bld(sd))).contactT.values.any { it != null } }
        val q = quiet.getOrNull(k)
        val qs = q?.let { (qn, qb) -> qn to pct(seeds.count { sd -> cons.run(qb(sd)).of(CueKind.STOP).isNotEmpty() }) }
        md.appendLine("| $name | ${pct(c)} | | ${qs?.first ?: ""} | ${qs?.second ?: ""} |")
    }
    md.appendLine()
    md.appendLine("S-09: the other pedestrian keeps walking at 1.3 m/s in the simulation, so contact after the user stops says")
    md.appendLine("nothing about the cue. Its timing is in the next table.")
    md.appendLine()
    md.appendLine("## STOP timing against open-loop contact")
    md.appendLine()
    md.appendLine("| Scenario | STOP later than 1.36 s before contact | No STOP at all | Minimum margin s | Median margin s |")
    md.appendLine("|---|---|---|---|---|")
    val timing: List<Pair<String, (Long) -> Scenario>> = listOf(
        "S-01 person standing" to { s -> Scenarios.s01Person(s) }, "S-03 bin" to { s -> Scenarios.s03Bin(s) },
        "S-04 head-height branch" to { s -> Scenarios.s04HeadHeight(s) },
        "S-09 pedestrian walking toward the user" to { s -> Scenarios.s09PersonToward(s) },
        "S-10 cyclist head-on at 4.5 m/s" to { s -> Scenarios.s10BikeToward(s) },
    )
    for ((name, b) in timing) {
        val ms = seeds.map { s -> val r = runner.run(b(s)); val c = r.contactT[1]; val st = r.of(CueKind.STOP).firstOrNull()
            if (c == null) Double.POSITIVE_INFINITY else if (st == null) Double.NEGATIVE_INFINITY else c - st.earT }
        val fin = ms.filter { it.isFinite() }.sorted()
        md.appendLine("| $name | ${pct(ms.count { it < 1.36 })} | ${pct(ms.count { it == Double.NEGATIVE_INFINITY })} | " +
            "%.2f | %.2f |".format(fin.firstOrNull() ?: Double.NaN, if (fin.isEmpty()) Double.NaN else fin[fin.size / 2]))
    }
    md.appendLine()
    md.appendLine("## Repetition and other review cases")
    md.appendLine()
    md.appendLine("| Case | Result |")
    md.appendLine("|---|---|")
    val s07 = seeds.map { runner.run(Scenarios.s07DoubleApproach(it)).of(CueKind.STOP).size }
    md.appendLine("| S-07 stop, back off, approach again: exactly two STOPs | ${pct(s07.count { it == 2 })} (counts seen: ${s07.groupingBy { it }.eachCount().toSortedMap()}) |")
    val s08 = seeds.map { runner.run(Scenarios.s08StopAndStand(it)).of(CueKind.STOP).size }
    md.appendLine("| S-08 stand in front of the obstacle: exactly one STOP | ${pct(s08.count { it == 1 })} (counts seen: ${s08.groupingBy { it }.eachCount().toSortedMap()}) |")
    val resume = seeds.count { s ->
        val r = runner.run(Scenario("resume", listOf(Obstacle(1, "bollard", 6.0, 0.0, 0.9, 0.2)), listOf(Segment(2.6, 1.4), Segment(5.0, 0.0), Segment(4.0, 1.4)), seed = s))
        r.of(CueKind.STOP).none { it.play.startT >= 7.6 } }
    md.appendLine("| Stop, stand 5 s, walk on: runs with no second STOP | ${pct(resume)} |")
    val dog = seeds.take(100).map { s -> runner.run(Scenario("dog", listOf(Obstacle(1, "dog", 1.0, 0.2, 0.6, 0.3, vx = 1.4)), listOf(Segment(60.0, 1.4)), seed = s)).of(CueKind.STOP) }
    md.appendLine("| Guide dog 1 m ahead for 60 s (100 runs): STOPs per minute | %.2f in total, of which %.2f after the first 5 s |"
        .format(dog.sumOf { it.size } / 100.0, dog.sumOf { d -> d.count { it.play.startT > 5.0 } } / 100.0))
    val crowd = seeds.take(100).map { runner.run(Scenarios.s19Crowd(it)) }
    md.appendLine("| S-19 crowd, 5 s (100 runs): cues heard per run | STOP %.1f, CAUTION or approaching %.1f |"
        .format(crowd.sumOf { it.of(CueKind.STOP).size } / 100.0, crowd.sumOf { r -> r.cues.count { it.kind == CueKind.CAUTION || it.kind == CueKind.MOVING_OBJECT } } / 100.0))
    File(out, "scenario_rates.md").writeText(md.toString())
    print(md)
}
